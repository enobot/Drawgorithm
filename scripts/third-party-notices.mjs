// Writes public/third-party-notices.txt: the licence of every production dependency the site
// ships (from package-lock.json, with each package's own licence file), plus the components
// that come inside Pyodide. MIT, OFL-1.1, MPL-2.0 and the PSF licence all ask that their
// notices travel with copies of the software; the build copies this file into dist/.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  fail if the file is out of date (used in CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'public/third-party-notices.txt';
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const pyodideVersion = JSON.parse(readFileSync('node_modules/pyodide/package.json', 'utf8')).version;
const pythonVersion = JSON.parse(readFileSync('node_modules/pyodide/pyodide-lock.json', 'utf8')).info.python;

const sections = [];
for (const [key, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  // Production packages only (dev tools are not shipped), and only ones actually installed.
  if (!key.startsWith('node_modules/') || entry.dev || !existsSync(key)) continue;
  const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const files = readdirSync(key).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f));
  const texts = files.map((f) => readFileSync(join(key, f), 'utf8').trim());
  const pkg = JSON.parse(readFileSync(join(key, 'package.json'), 'utf8'));
  const source = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  sections.push(
    [
      `${name} ${entry.version} (${entry.license ?? pkg.license ?? 'licence not stated'})`,
      source ? `Source: ${source.replace(/^git\+/, '')}` : null,
      texts.length ? texts.join('\n\n') : `The package includes no licence file; its package.json states ${pkg.license}.`,
    ]
      .filter(Boolean)
      .join('\n'),
  );
}

// Inside pyodide (served from /pyodide/): CPython compiled to WebAssembly and its standard library.
sections.push(
  [
    `Pyodide ${pyodideVersion} (MPL-2.0), served unmodified from /pyodide/`,
    `The Source Code Form is available at https://github.com/pyodide/pyodide/tree/${pyodideVersion} and is governed by the`,
    'Mozilla Public License, version 2.0: https://www.mozilla.org/MPL/2.0/',
  ].join('\n'),
  [
    `CPython ${pythonVersion} (PSF License Agreement and the licences of incorporated software), inside Pyodide`,
    'Copyright © 2001 Python Software Foundation; All Rights Reserved.',
    `Licence terms: https://docs.python.org/${pythonVersion.split('.').slice(0, 2).join('.')}/license.html`,
    `Source: https://github.com/python/cpython/tree/v${pythonVersion}`,
  ].join('\n'),
);

const text = [
  'Drawgorithms includes the following third-party software and fonts. Each is used under its',
  'licence, reproduced or linked below. Generated by scripts/third-party-notices.mjs.',
  '',
  ...sections.map((s) => `${'='.repeat(78)}\n${s}\n`),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error(`${OUT} is out of date: run node scripts/third-party-notices.mjs and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${sections.length} components).`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${sections.length} components).`);
}
